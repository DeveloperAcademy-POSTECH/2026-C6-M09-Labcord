struct CatalogPrimitiveGroup: Identifiable, Sendable {
    let id: String
    let title: String
    let swatches: [CatalogPrimitiveSwatch]
}

struct CatalogPrimitiveSwatch: Identifiable, Sendable {
    let name: String
    let label: String
    var id: String { name }
    var hasBorder: Bool { name == "Neutral/0" || name.hasPrefix("WhiteAlpha/") }
    var gradientEdge: VerticalEdge? {
        switch name {
        case "Gradient/Fade/Top": .top
        case "Gradient/Fade/Bottom": .bottom
        default: nil
        }
    }
}

struct CatalogPrimitiveRGBA: Sendable {
    let red: Double
    let green: Double
    let blue: Double
    let opacity: Double

    init(_ red: Double, _ green: Double, _ blue: Double, _ opacity: Double) {
        self.red = red
        self.green = green
        self.blue = blue
        self.opacity = opacity
    }

    var color: Color { Color(.sRGB, red: red, green: green, blue: blue, opacity: opacity) }
    var hex: String {
        let channels = opacity < 1 ? [red, green, blue, opacity] : [red, green, blue]
        let values = channels.map { Int(($0 * 255).rounded()) }
        return "#" + values.map { String(format: "%02X", $0) }.joined()
    }
    var description: String {
        let rgb = [red, green, blue].map { String(Int(($0 * 255).rounded())) }
        return "R \(rgb[0]) · G \(rgb[1]) · B \(rgb[2]) · A \(Int((opacity * 100).rounded()))%"
    }
}
